"""Build the offline 5-degree climate atlas from NOAA monthly normals.

Usage: python build-climate.py /path/to/{directory containing sst.nc,uwnd.nc,vwnd.nc}
Requires numpy and netCDF4 at build time only. Inputs (1991-2020):
https://downloads.psl.noaa.gov/Datasets/noaa.ersst.v5/sst.mon.ltm.1991-2020.nc
https://downloads.psl.noaa.gov/Datasets/ncep.reanalysis.derived/pressure/{u,v}wnd.mon.ltm.1991-2020.nc
"""
import base64
import sys
from pathlib import Path

import numpy as np
from netCDF4 import Dataset

inputs = Path(sys.argv[1])
latitudes = np.arange(-85, 86, 5)
longitudes = np.arange(0, 360, 5)

with Dataset(inputs / 'sst.nc') as source:
    # Wet ocean samples only; don't treat land fill values as freezing water.
    field = source['sst'][:].filled(np.nan)
    lats, lons = source['lat'][:], source['lon'][:]
    sst = np.full((12, len(latitudes), len(longitudes)), np.nan)
    for y, lat in enumerate(latitudes):
        for x, lon in enumerate(longitudes):
            tile = field[:, np.abs(lats - lat) <= 2.5][:, :, np.abs((lons-lon+180) % 360-180) <= 2.5]
            count = np.isfinite(tile).sum(axis=(1, 2))
            sst[:, y, x] = np.nansum(tile, axis=(1, 2)) / np.where(count, count, np.nan)

def layer_difference(key):
    with Dataset(inputs / (key + '.nc')) as source:
        levels = list(source['level'][:])
        delta = source[key][:, levels.index(200)] - source[key][:, levels.index(850)]
        y = [list(source['lat'][:]).index(lat) for lat in latitudes]
        x = [list(source['lon'][:]).index(lon) for lon in longitudes]
        return delta[:, y][:, :, x]

# Magnitude of the monthly mean 200-850 hPa vector difference, NOT mean
# instantaneous shear. The simulation overlays its own synoptic variability.
shear = np.hypot(layer_difference('uwnd'), layer_difference('vwnd'))
packed = np.stack((np.where(np.isfinite(sst), np.clip(np.rint((sst+2)*5),0,254), 255),
                   np.clip(np.rint(shear*4),0,254)), axis=-1).astype('uint8')
data = base64.b64encode(packed.tobytes()).decode('ascii')
output = Path(__file__).resolve().parents[1] / 'dist' / 'monthly-normals.generated.js'
output.write_text('// Generated by build-climate.py; 1991–2020 ERSSTv5 + NCEP/NCAR, NOAA PSL.\n'
                  + "export const packedNormals = '" + data + "';\n", encoding='utf-8')
